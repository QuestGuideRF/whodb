package source
type ExternalModel struct {
	Type     string
	Token    string
	Model    string
	Endpoint string
}
type Record struct {
	Key   string            `json:"Key"`
	Value string            `json:"Value"`
	Extra map[string]string `json:"Extra,omitempty"`
}
type StorageUnit struct {
	Name       string
	Attributes []Record
}
type Column struct {
	Type             string
	Name             string
	IsNullable       bool
	IsPrimary        bool
	IsAutoIncrement  bool
	IsComputed       bool
	IsForeignKey     bool
	ReferencedTable  *string
	ReferencedColumn *string
	Length           *int
	Precision        *int
	Scale            *int
}
type RowsResult struct {
	Columns       []Column
	Rows          [][]string
	DisableUpdate bool
	TotalCount    int64
}
type ContentResult struct {
	Text       *string
	MIMEType   string
	IsBinary   bool
	SizeBytes  int64
	Truncated  bool
	FileName   string
	ModifiedAt *string
}
type GraphRelationshipType string
const (
	GraphRelationshipTypeOneToOne GraphRelationshipType = "OneToOne"
	GraphRelationshipTypeOneToMany GraphRelationshipType = "OneToMany"
	GraphRelationshipTypeManyToOne GraphRelationshipType = "ManyToOne"
	GraphRelationshipTypeManyToMany GraphRelationshipType = "ManyToMany"
	GraphRelationshipTypeUnknown GraphRelationshipType = "Unknown"
)
type GraphRelationship struct {
	Name             string
	RelationshipType GraphRelationshipType
	SourceColumn     *string
	TargetColumn     *string
}
type GraphUnit struct {
	Unit      StorageUnit
	Relations []GraphRelationship
}
type ChatMessage struct {
	Type                 string
	Result               *RowsResult
	Text                 string
	RequiresConfirmation bool
}
type ForeignKeyRelationship struct {
	ColumnName       string
	ReferencedTable  string
	ReferencedColumn string
}
type SSLStatus struct {
	IsEnabled bool
	Mode      string
}
type SSLModeInfo struct {
	Value       string
	Label       string
	Description string
	Aliases     []string
}
type TypeSessionMetadata struct {
	TypeDefinitions []TypeDefinition
	Operators       []string
	AliasMap        map[string]string
}
type DiscoveryPrefill struct {
	AdvancedDefaults []DiscoveryAdvancedDefault
}
type DiscoveryAdvancedDefault struct {
	Key           string
	Value         string
	MetadataKey   string
	DefaultValue  string
	ProviderTypes []string
	Conditions    []DiscoveryMetadataCondition
}
type DiscoveryMetadataCondition struct {
	Key   string
	Value string
}
type TypeCategory string
const (
	TypeCategoryNumeric TypeCategory = "numeric"
	TypeCategoryText TypeCategory = "text"
	TypeCategoryBinary TypeCategory = "binary"
	TypeCategoryDatetime TypeCategory = "datetime"
	TypeCategoryBoolean TypeCategory = "boolean"
	TypeCategoryJSON TypeCategory = "json"
	TypeCategoryOther TypeCategory = "other"
)
type TypeDefinition struct {
	ID               string
	Label            string
	HasLength        bool
	HasPrecision     bool
	DefaultLength    *int
	DefaultPrecision *int
	Category         TypeCategory
	InsertFunc       string
	TableModel       string
	DDLSuffix        string
}
type ImportMode string
const (
	ImportModeAppend ImportMode = "APPEND"
	ImportModeOverwrite ImportMode = "OVERWRITE"
	ImportModeUpsert ImportMode = "UPSERT"
)
type ParsedImportFile struct {
	Columns   []string
	Rows      [][]string
	Truncated bool
	Sheet     string
}
type ImportColumnMapping struct {
	SourceColumn string
	TargetColumn *string
	Skip         bool
}
type ImportRequest struct {
	Mode               ImportMode
	Parsed             ParsedImportFile
	Mapping            []ImportColumnMapping
	AllowAutoGenerated bool
	BatchSize          int
}
type ImportResult struct {
	RowsImported int
}
type QuerySuggestion struct {
	Description string
	Category    string
}
